
from pathlib import Path
import pandas as pd

# Project paths
PROJECT_DIR = Path(__file__).resolve().parent.parent

DATA_FILE = (
    PROJECT_DIR / "data" / "processed"
    / "developer_performance_summary.csv"
)

REPORT_DIR = PROJECT_DIR / "reports"
REPORT_FILE = REPORT_DIR / "Developer_Performance_Insights.md"


def main():
    print("Generating Developer Performance Insights Report...")

    if not DATA_FILE.exists():
        print("ERROR: Performance summary dataset not found.")
        return

    df = pd.read_csv(DATA_FILE)

    required_columns = [
        "developer_id",
        "average_productivity",
        "average_focus",
        "average_workload",
        "total_coding_hours",
        "high_flow_sessions",
        "high_flow_percentage"
    ]

    missing_columns = [
        col for col in required_columns if col not in df.columns
    ]

    if missing_columns:
        print("ERROR: Missing columns:", missing_columns)
        return

    # Identify top performers
    best_productivity = df.loc[df["average_productivity"].idxmax()]
    best_focus = df.loc[df["average_focus"].idxmax()]
    most_flow = df.loc[df["high_flow_sessions"].idxmax()]

    # Overall statistics
    avg_productivity = df["average_productivity"].mean()
    avg_focus = df["average_focus"].mean()
    avg_workload = df["average_workload"].mean()

    total_sessions = int(df["total_sessions"].sum())
    total_flow_sessions = int(df["high_flow_sessions"].sum())

    # Create report
    report = f"""# CogniStream: Developer Performance Insights

## 1. Introduction

This report presents a comparative analysis of developer performance
using the CogniStream synthetic developer activity dataset.

## 2. Overall Performance Summary

- Total developers analyzed: {len(df)}
- Total work sessions: {total_sessions}
- Average productivity score: {avg_productivity:.2f}
- Average focus score: {avg_focus:.2f}
- Average workload score: {avg_workload:.2f}
- Total high-flow sessions: {total_flow_sessions}

## 3. Key Performance Highlights

- Highest average productivity: {best_productivity['developer_id']}
  ({best_productivity['average_productivity']:.2f})
- Highest average focus: {best_focus['developer_id']}
  ({best_focus['average_focus']:.2f})
- Most high-flow sessions: {most_flow['developer_id']}
  ({int(most_flow['high_flow_sessions'])} sessions)

## 4. Developer Comparison

| Developer | Productivity | Focus | Workload | High Flow Sessions |
|---|---:|---:|---:|---:|
"""

    for _, row in df.sort_values(
        "average_productivity", ascending=False
    ).iterrows():
        report += (
            f"| {row['developer_id']} "
            f"| {row['average_productivity']:.2f} "
            f"| {row['average_focus']:.2f} "
            f"| {row['average_workload']:.2f} "
            f"| {int(row['high_flow_sessions'])} |\n"
        )

    report += f"""
## 5. Recommendations

1. Encourage focused work periods to support productivity.
2. Review workload distribution to avoid excessive cognitive load.
3. Reduce unnecessary interruptions and task switching.
4. Encourage regular breaks during long coding sessions.
5. Study high-flow work patterns to identify helpful practices.

## 6. Conclusion

The analysis highlights differences in productivity, focus, workload,
and flow-state sessions across the five developers.

These results are exploratory and are based on synthetic data.
They do not establish causal relationships or measure actual
employee performance.

---
Generated by the CogniStream analytics project.
"""

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_FILE.write_text(report, encoding="utf-8")

    print("\nReport generated successfully!")
    print("Developers analyzed:", len(df))
    print("Total sessions:", total_sessions)
    print("Top productivity developer:", best_productivity["developer_id"])
    print("Report saved at:", REPORT_FILE)


if __name__ == "__main__":
    main()
